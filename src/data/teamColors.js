/**
 * 2026 시즌 F1 팀 컬러.
 *
 * 순위표와 포인트 추이 차트에서 팀을 구분하는 데 쓴다.
 * 값은 각 팀이 2026 리버리를 공개할 때 알려진 대표 색이다.
 *
 * 두 곳은 그대로 쓸 수 없어 판단이 들어갔고, 이유를 남긴다.
 *
 * - audi: 리버리는 티타늄 실버가 넓고 레드가 포인트다. 실버를 쓰면
 *   하스(회색)·캐딜락(흰검)과 뒤엉켜 선을 구분할 수 없어서 레드를 골랐다.
 *   페라리보다 어두운 아우디 브랜드 레드라 나란히 놓아도 갈린다.
 *
 * - cadillac: 차 한쪽이 검정, 반대쪽이 흰색인 리버리다. 검정은 다크 테마에서,
 *   흰색은 라이트 테마에서 배경에 묻힌다. 두 테마 모두에서 보이는
 *   중간 명도의 그래파이트로 잡았다.
 *
 * 파랑 계열이 넷(레드불·레이싱불스·알핀·윌리엄스)이라 색만으로는 붙어 있을 때
 * 헷갈릴 수 있다. 그래서 차트는 범례에만 기대지 않고 선 끝에 팀 이름을 직접 붙인다.
 */
export const TEAM_COLORS = {
  mercedes: '#00D7B6',
  ferrari: '#ED1131',
  mclaren: '#FF8000',
  red_bull: '#4781D7',
  rb: '#6C98FF',
  alpine: '#00A1E8',
  aston_martin: '#229971',
  williams: '#1868DB',
  haas: '#9C9FA2',
  audi: '#BB0A30',
  cadillac: '#7A828A',
}

/** 팀 색. 모르는 팀이면 테마 강조색으로 넘긴다. */
export const colorOf = (constructorId) => TEAM_COLORS[constructorId] ?? 'var(--accent, #00d2be)'

/**
 * 한 팀에 드라이버가 둘이라 색만으로는 팀메이트를 못 가른다.
 * 팀 안에서 순위가 앞선 쪽을 실선, 뒤쪽을 파선으로 그린다.
 */
export const dashFor = (indexWithinTeam) => (indexWithinTeam === 0 ? [] : [6, 4])
