/**
 * 표에 없는 코드는 대분류로라도 자연스럽게 옮긴다.
 * 정의된 범위를 벗어나면 null을 반환해 API 원문으로 폴백되게 한다.
 */
const fallbackByRange = (id) => {
  if (!Number.isFinite(id)) return null
  if (id >= 200 && id < 300) return '천둥번개'
  if (id >= 300 && id < 400) return '이슬비'
  if (id >= 500 && id < 600) return '비'
  if (id >= 600 && id < 700) return '눈'
  if (id >= 700 && id < 800) return '안개'
  if (id === 800) return '맑음'
  if (id > 800 && id < 900) return '구름'
  return null
}

/**
 * @param {number} id  OpenWeatherMap 날씨 코드
 * @param {string} apiText  API가 준 설명 (표에도 범위에도 없을 때의 최후 폴백)
 */
export const describeWeather = (id, apiText = '') =>
  WEATHER_TEXT[id] ?? fallbackByRange(Number(id)) ?? apiText ?? ''

export default WEATHER_TEXT
